"""
Izalith Trading System - Telegram Notifier
"""
import html
import aiohttp
from typing import Optional, Dict, List
from datetime import datetime, timezone

from .detector import Signal
from core.utils.logger import get_logger

logger = get_logger("telegram")


class TelegramNotifier:
    """Sends trading signals to Telegram."""

    API_URL = "https://api.telegram.org/bot{token}"

    def __init__(self, bot_token: str, chat_id: str):
        self.bot_token = bot_token
        self.chat_id = chat_id
        self._session: Optional[aiohttp.ClientSession] = None
        self.enabled = bool(bot_token and chat_id)

    async def _get_session(self) -> aiohttp.ClientSession:
        """Get or create HTTP session."""
        if self._session is None or self._session.closed:
            self._session = aiohttp.ClientSession()
        return self._session

    async def close(self) -> None:
        """Close the HTTP session."""
        if self._session and not self._session.closed:
            await self._session.close()

    def _format_signal_message(self, signal: Signal) -> str:
        """Format a signal as a Telegram message."""
        emoji = "🟢" if signal.direction == "bullish" else "🔴"
        direction = signal.direction.upper()

        # Format price based on magnitude
        if signal.price >= 1000:
            price_str = f"${signal.price:,.2f}"
        elif signal.price >= 1:
            price_str = f"${signal.price:.4f}"
        else:
            price_str = f"${signal.price:.6f}"

        # Signal type mapping
        signal_names = {
            "rsi_oversold": "RSI Oversold",
            "rsi_overbought": "RSI Overbought",
            "macd_bullish_cross": "MACD Bullish Cross",
            "macd_bearish_cross": "MACD Bearish Cross",
            "bollinger_lower": "Bollinger Lower Band",
            "bollinger_upper": "Bollinger Upper Band",
            "volume_spike_bullish": "Bullish Volume Spike",
            "volume_spike_bearish": "Bearish Volume Spike",
            "breakout_high": "Breakout (High)",
            "breakout_low": "Breakdown (Low)"
        }
        signal_name = signal_names.get(signal.signal_type, signal.signal_type)

        # HTML en lugar de Markdown: un guion bajo (EUR_USD) rompía el formato y Telegram rechazaba el mensaje
        e = html.escape
        message = f"""
{emoji} <b>{direction} SIGNAL</b> - {e(signal.symbol)}

<b>Type:</b> {e(signal_name)}
<b>Price:</b> {e(price_str)}
<b>Strength:</b> {signal.strength:.0%}

{e(signal.message)}

<i>Time: {signal.timestamp.strftime('%H:%M:%S UTC')}</i>
"""
        return message.strip()

    async def send_signal(self, signal: Signal) -> bool:
        """Send a single signal to Telegram."""
        if not self.enabled:
            logger.debug("Telegram not configured, skipping signal")
            return False

        try:
            session = await self._get_session()
            url = f"{self.API_URL.format(token=self.bot_token)}/sendMessage"

            message = self._format_signal_message(signal)

            payload = {
                "chat_id": self.chat_id,
                "text": message,
                "parse_mode": "HTML",
                "disable_web_page_preview": True
            }

            async with session.post(url, json=payload) as resp:
                if resp.status == 200:
                    logger.info(f"Signal sent to Telegram: {signal.symbol} {signal.signal_type}")
                    return True
                else:
                    error = await resp.text()
                    logger.error(f"Telegram error {resp.status}: {error}")
                    return False

        except Exception as e:
            logger.error(f"Failed to send Telegram message: {e}")
            return False

    async def send_daily_summary(self, stats: Dict) -> bool:
        """Send a daily summary to Telegram."""
        if not self.enabled:
            return False

        try:
            session = await self._get_session()
            url = f"{self.API_URL.format(token=self.bot_token)}/sendMessage"

            signals_count = stats.get('signals_count', 0)
            bullish = stats.get('bullish_count', 0)
            bearish = stats.get('bearish_count', 0)
            trades = stats.get('trades_count', 0)
            pnl = stats.get('realized_pnl', 0)

            pnl_emoji = "📈" if pnl >= 0 else "📉"

            message = f"""
📊 <b>DAILY SUMMARY</b> - {datetime.now(timezone.utc).strftime('%Y-%m-%d')}

<b>Signals Detected:</b> {signals_count}
  🟢 Bullish: {bullish}
  🔴 Bearish: {bearish}

<b>Trades Executed:</b> {trades}
{pnl_emoji} <b>Realized P/L:</b> ${pnl:+,.2f}

<i>Generated by Izalith Trading System</i>
"""

            payload = {
                "chat_id": self.chat_id,
                "text": message.strip(),
                "parse_mode": "HTML"
            }

            async with session.post(url, json=payload) as resp:
                if resp.status == 200:
                    logger.info("Daily summary sent to Telegram")
                    return True
                else:
                    error = await resp.text()
                    logger.error(f"Telegram error {resp.status}: {error}")
                    return False

        except Exception as e:
            logger.error(f"Failed to send daily summary: {e}")
            return False

    async def send_alert(self, title: str, message: str, level: str = "info") -> bool:
        """Send a generic alert message."""
        if not self.enabled:
            return False

        emoji_map = {
            "info": "ℹ️",
            "warning": "⚠️",
            "error": "🚨",
            "success": "✅"
        }
        emoji = emoji_map.get(level, "ℹ️")

        try:
            session = await self._get_session()
            url = f"{self.API_URL.format(token=self.bot_token)}/sendMessage"

            text = f"{emoji} <b>{html.escape(title)}</b>\n\n{html.escape(message)}"

            payload = {
                "chat_id": self.chat_id,
                "text": text,
                "parse_mode": "HTML"
            }

            async with session.post(url, json=payload) as resp:
                return resp.status == 200

        except Exception as e:
            logger.error(f"Failed to send alert: {e}")
            return False

    async def test_connection(self) -> bool:
        """Test the Telegram connection."""
        if not self.enabled:
            logger.warning("Telegram not configured")
            return False

        try:
            session = await self._get_session()
            url = f"{self.API_URL.format(token=self.bot_token)}/getMe"

            async with session.get(url) as resp:
                if resp.status == 200:
                    data = await resp.json()
                    bot_name = data.get('result', {}).get('username', 'Unknown')
                    logger.info(f"Telegram connected as @{bot_name}")
                    return True
                else:
                    logger.error(f"Telegram connection failed: {resp.status}")
                    return False

        except Exception as e:
            logger.error(f"Telegram connection test failed: {e}")
            return False
